const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('dist/news.js', 'utf8');
const context = vm.createContext({ URL, Date, CURATED_PROJECTS: [] });
vm.runInContext(source.slice(source.indexOf('function httpsURL'), source.indexOf('function renderNews')), context);
const game = {id:'demo',repo:'owner/game',title:'Game',type:'source-port',url:'https://github.com/owner/game',last_commit:'2026-01-02',release:'v1',release_date:'2026-01-01'};
const collect = games => context.collectNews({generated_at:'2026-01-03',games});
let events = collect([game, {...game}]);
assert.equal(events.length, 2, 'Duplicate repositories must not duplicate events');
assert.equal(events[0].kind, 'activity');
assert.equal(events[1].kind, 'release');
assert.equal(events[1].url, game.url+'/releases');
assert.equal(collect([{...game,url:'javascript:alert(1)'}]).length,0);
assert.equal(collect([{...game,type:'decompilation'}]).length,0);
assert.equal(collect([{...game,last_commit:'invalid',release_date:'2999-01-01'}]).length,0);
assert.equal(collect([{...game,release:null}]).length,1);
assert.throws(()=>context.collectNews({games:[]}));
const actual = context.collectNews(JSON.parse(fs.readFileSync('dist/catalog.json','utf8')));
assert.ok(actual.some(e=>e.kind==='release'));
assert.ok(actual.every((e,i)=>!i||actual[i-1].time>=e.time));
console.log('PASS: novidades com datas válidas, ordem cronológica, deduplicação e links seguros.');
