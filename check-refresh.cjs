const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const nodes=new Map();
const node=s=>{if(!nodes.has(s))nodes.set(s,{value:s==='#sort'?'featured':'',checked:false,disabled:false,textContent:'',innerHTML:''});return nodes.get(s)};
let imageHandlers=0;
const image={addEventListener(type){assert.equal(type,'error');imageHandlers++}};
const document={querySelector:node,querySelectorAll:s=>s==='.project-cover img'?[image]:[]};
const data=JSON.parse(fs.readFileSync('dist/catalog.json','utf8'));
let offline=false;
const ctx=vm.createContext({document,URL,Date,console,AbortSignal,localStorage:{getItem:()=>null,setItem(){}},fetch:async()=>{if(offline)throw new TypeError('Failed to fetch');return {ok:true,json:async()=>data}}});
vm.runInContext(fs.readFileSync('dist/app.js','utf8').split("// Catalog page bootstrap")[0],ctx);
(async()=>{
 await vm.runInContext('refresh()',ctx);
 assert.equal(node('#syncLabel').textContent,'Sincronizado com a base');
 assert.equal(node('#refresh').disabled,false);
 assert(imageHandlers>0,'Render must bind image fallback without throwing');
 assert(node('#grid').innerHTML.includes('project-cover'));
 const previousGrid=node('#grid').innerHTML;
 offline=true;
 await vm.runInContext('refresh()',ctx);
 await vm.runInContext('refresh()',ctx);
 assert.equal(node('#grid').innerHTML,previousGrid,'Failed refresh preserves cards');
 assert.equal((node('#syncDate').textContent.match(/cópia disponível/g)||[]).length,1);
 assert.equal(node('#refresh').disabled,false);
 offline=false;
 await vm.runInContext('refresh()',ctx);
 assert.equal(node('#syncLabel').textContent,'Sincronizado com a base','Retry recovers');
 vm.runInContext('refreshCurated=async()=>{throw Error("render failure")}',ctx);
 await vm.runInContext('refresh()',ctx);
 assert.equal(node('#refresh').disabled,false,'Supplement failure releases button');
 assert.equal(vm.runInContext('busy',ctx),false);
 console.log('PASS: render, atualização, falha de rede, repetição, recuperação e desbloqueio.');
})().catch(e=>{console.error(e);process.exitCode=1});
